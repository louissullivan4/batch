#!/usr/bin/env node
/**
 * Generates `src/auth/staff-fixture.ts` — a small, committed set of rostered staff with REAL Argon2id
 * PHC hashes (ADR 0009), standing in for the back-office staff sync that doesn't exist yet (mirrors
 * the Sprint 3 menu fixture, A-017; logged as assumption A-0xx in docs/assumptions.md).
 *
 * The dev PINs live ONLY in this script, never in the shipped fixture — `staff-fixture.ts` carries
 * PHC strings only. Run: `pnpm --filter @batch/till staff:fixture:gen`. Deterministic salts are NOT
 * used (each run re-salts and re-hashes), so re-running regenerates different-looking but
 * functionally identical hashes — commit the output once and leave it alone.
 */

import { randomBytes } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import { argon2id } from 'hash-wasm'

// Dev PINs for the seed roster — NOT shipped. Change these here and re-run the script to rotate them.
const STAFF = [
  { id: 'staff-orla', name: 'Orla', role: 'MANAGER', pin: '0000' },
  { id: 'staff-kyle', name: 'Kyle', role: 'MANAGER', pin: '0000' },
  { id: 'staff-jerry', name: 'Jerry', role: 'MANAGER', pin: '0000' },
  { id: 'staff-evan', name: 'Evan', role: 'STAFF', pin: '0000' },
]

// ADR 0009 floor: m = 19456 KiB, t = 2, p = 1, 16-byte random salt, PHC output.
async function hashPin(pin) {
  const salt = randomBytes(16)
  return argon2id({
    password: pin,
    salt,
    iterations: 2,
    parallelism: 1,
    memorySize: 19456,
    hashLength: 32,
    outputType: 'encoded',
  })
}

async function main() {
  const entries = []
  for (const s of STAFF) {
    const pinPhc = await hashPin(s.pin)
    entries.push({ id: s.id, name: s.name, role: s.role, pinPhc })
  }

  const body = entries
    .map(
      (e) =>
        `  { id: ${JSON.stringify(e.id)}, name: ${JSON.stringify(e.name)}, role: ${JSON.stringify(e.role)}, pinPhc: ${JSON.stringify(e.pinPhc)} },`,
    )
    .join('\n')

  const out = `/**
 * GENERATED by \`scripts/gen-staff-fixture.mjs\` — do not edit by hand. Regenerate:
 *   pnpm --filter @batch/till staff:fixture:gen
 *
 * A seed staff roster (ADR 0009), standing in for back-office staff sync (Sprint 6), which doesn't
 * exist yet — assumption in docs/assumptions.md, falsifier: back office ships staff sync. Every
 * \`pinPhc\` is a REAL Argon2id PHC string (m=19456, t=2, p=1, 16-byte random salt); the dev PINs used
 * to produce them are NOT here — see the generator script's header comment.
 */

export type StaffRole = 'MANAGER' | 'STAFF'

export interface StaffFixtureEntry {
  readonly id: string
  readonly name: string
  readonly role: StaffRole
  /** Argon2id PHC string — \`verifyPin\` (src/auth/pin.ts) checks a typed PIN against this. */
  readonly pinPhc: string
}

export const STAFF_FIXTURE: readonly StaffFixtureEntry[] = [
${body}
]
`

  await writeFile(new URL('../src/auth/staff-fixture.ts', import.meta.url), out)
  console.log(`wrote ${entries.length} staff fixture entries to src/auth/staff-fixture.ts`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
